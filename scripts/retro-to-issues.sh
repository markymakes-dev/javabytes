#!/usr/bin/env bash
# Retro-Issue Loop: Convert /retro findings into GitHub issues
# Usage: ./retro-to-issues.sh <retrospective-file> [source-path] [ui-strategy]
# Requires: gh CLI authenticated, jq installed

set -euo pipefail

RETRO_FILE="${1:-}"
SOURCE_PATH="${2:-unknown}"
UI_STRATEGY="${3:-unknown}"

if [[ ! -f "$RETRO_FILE" ]]; then
    echo "Usage: $0 <retrospective-file> [source-path] [ui-strategy]"
    exit 1
fi

REPO="markymakes-dev/javabytes"

# Extract tooling gaps from retrospective markdown
# Expected format: "### Tooling Gaps" followed by list items with tool names
# Example:
# ### Tooling Gaps
# - translate_webapp: didn't handle JSX in components
# - extract_data_models: missed Prisma enum types

echo "Parsing retrospective: $RETRO_FILE"

# Create a temporary file for issue bodies
TMP_DIR=$(mktemp -d)
trap 'rm -rf "$TMP_DIR"' EXIT

# Parse the retrospective for tooling gaps
# Look for lines like "- tool_name: description" under "### Tooling Gaps" section
IN_GAPS=false
ISSUE_COUNT=0

while IFS= read -r line; do
    if [[ "$line" =~ ^###\ Tooling\ Gaps ]]; then
        IN_GAPS=true
        continue
    fi
    
    if [[ "$IN_GAPS" == true && "$line" =~ ^### ]]; then
        # Next section started
        IN_GAPS=false
        continue
    fi
    
    if [[ "$IN_GAPS" == true && "$line" =~ ^[[:space:]]*-[[:space:]]*([a-zA-Z_][a-zA-Z0-9_]*):[[:space:]]*(.+) ]]; then
        TOOL_NAME="${BASH_REMATCH[1]}"
        GAP_DESC="${BASH_REMATCH[2]}"
        
        ISSUE_COUNT=$((ISSUE_COUNT + 1))
        
        # Create issue body
        cat > "$TMP_DIR/issue_$ISSUE_COUNT.md" <<EOF
## Retro Finding: $TOOL_NAME

**Source Path:** $SOURCE_PATH  
**UI Strategy:** $UI_STRATEGY  
**Tool:** \`$TOOL_NAME\`  
**Gap:** $GAP_DESC  

### Context
This issue was automatically created from a \`/retro\` session after a JavaBytes conversion.

**Conversion Details:**
- Source app: \`$SOURCE_PATH\`
- UI strategy: \`$UI_STRATEGY\`
- Generated by: retro-issue-loop (ADR 0011)

### Reproduction
1. Run JavaBytes conversion pipeline on the source app
2. Observe the manual work inventory for \`$TOOL_NAME\`
3. The gap described above should appear as manual work

### Expected Behavior
\`$TOOL_NAME\` should handle this pattern automatically without manual intervention.

### Actual Behavior
Manual work required: $GAP_DESC

### Labels
\`retro\`, \`needs-triage\`, \`$TOOL_NAME\`
EOF

        echo "Creating issue $ISSUE_COUNT for $TOOL_NAME..."
        
        # Create the GitHub issue
        gh issue create \
            --repo "$REPO" \
            --title "[retro] $TOOL_NAME — $GAP_DESC" \
            --body-file "$TMP_DIR/issue_$ISSUE_COUNT.md" \
            --label "retro,needs-triage,$TOOL_NAME" \
            || echo "Warning: Failed to create issue for $TOOL_NAME (may already exist or auth issue)"

    fi
done < "$RETRO_FILE"

if [[ $ISSUE_COUNT -eq 0 ]]; then
    echo "No tooling gaps found in retrospective (looking for '### Tooling Gaps' section with '- tool: description' format)"
    exit 0
fi

echo "Created $ISSUE_COUNT GitHub issue(s) in $REPO"
echo "Issues tagged with: retro, needs-triage, <tool-name>"
echo "Next: run /triage to process them"