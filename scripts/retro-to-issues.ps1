#!/usr/bin/env pwsh
# Retro-Issue Loop: Convert /retro findings into GitHub issues (Windows PowerShell)
# Usage: ./retro-to-issues.ps1 -RetroFile <path> [-SourcePath <path>] [-UiStrategy <strategy>]
# Requires: gh CLI authenticated, jq installed

param(
    [Parameter(Mandatory=$true)]
    [string]$RetroFile,

    [string]$SourcePath = "unknown",
    [string]$UiStrategy = "unknown"
)

if (-not (Test-Path $RetroFile)) {
    Write-Error "Retrospective file not found: $RetroFile"
    exit 1
}

$Repo = "markymakes-dev/javabytes"
$TmpDir = New-Item -ItemType Directory -Force -Path ([System.IO.Path]::GetTempPath() + "retro-issues-" + [Guid]::NewGuid().ToString())

try {
    $Content = Get-Content $RetroFile -Raw
    $InGaps = $false
    $IssueCount = 0

    $Lines = $Content -split "`r?`n"
    foreach ($Line in $Lines) {
        if ($Line -match '^###\s+Tooling\s+Gaps') {
            $InGaps = $true
            continue
        }

        if ($InGaps -and $Line -match '^###') {
            $InGaps = $false
            continue
        }

        if ($InGaps -and $Line -match '^\s*-\s*([a-zA-Z_][a-zA-Z0-9_]*):\s*(.+)') {
            $ToolName = $Matches[1]
            $GapDesc = $Matches[2]

            $IssueCount++
            $IssueFile = Join-Path $TmpDir.FullName "issue_$IssueCount.md"

            @"
## Retro Finding: $ToolName

**Source Path:** $SourcePath  
**UI Strategy:** $UiStrategy  
**Tool:** \`$ToolName\`  
**Gap:** $GapDesc  

### Context
This issue was automatically created from a \`/retro\` session after a JavaBytes conversion.

**Conversion Details:**
- Source app: \`$SourcePath\`
- UI strategy: \`$UiStrategy\`
- Generated by: retro-issue-loop (ADR 0011)

### Reproduction
1. Run JavaBytes conversion pipeline on the source app
2. Observe the manual work inventory for \`$ToolName\`
3. The gap described above should appear as manual work

### Expected Behavior
\`$ToolName\` should handle this pattern automatically without manual intervention.

### Actual Behavior
Manual work required: $GapDesc

### Labels
\`retro\`, \`needs-triage\`, \`$ToolName\`
"@ | Set-Content $IssueFile -Encoding UTF8

            Write-Host "Creating issue $IssueCount for $ToolName..."
            
            try {
                gh issue create `
                    --repo $Repo `
                    --title "[retro] $ToolName -- $GapDesc" `
                    --body-file $IssueFile `
                    --label "retro,needs-triage,$ToolName"
            } catch {
                Write-Warning "Failed to create issue for $ToolName: $_"
            }
        }
    }

    if ($IssueCount -eq 0) {
        Write-Host "No tooling gaps found in retrospective (looking for '### Tooling Gaps' section with '- tool: description' format)"
        exit 0
    }

    Write-Host "Created $IssueCount GitHub issue(s) in $Repo"
    Write-Host "Issues tagged with: retro, needs-triage, <tool-name>"
    Write-Host "Next: run /triage to process them"

} finally {
    if (Test-Path $TmpDir.FullName) {
        Remove-Item -Recurse -Force $TmpDir.FullName
    }
}